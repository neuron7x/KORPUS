"""Межа обертів розкодування: гілка, якої не брав жоден прогін.

Вимір покриття гілок 04.09.2026. Вхід тут ЧУЖИЙ — це завантажений документ, — тож
поведінка на його межі є властивістю системи, а не деталлю реалізації.

Сусідній `_hard_chunks` теж має невзяті дуги, і їх тут НЕМАЄ навмисно: цю функцію
не викликає жоден модуль продакшену, лише тести. Покривати її означало б рухати
число ратчета на коді, який ніщо не виконує. Її стан записано окремо як знахідку.
"""

from __future__ import annotations

from korpus.infrastructure.extraction import (
    MAX_UNESCAPE_ROUNDS,
    _RESIDUAL_MARKUP,
    _strip_html,
)


def test_markup_that_survives_every_round_is_returned_rather_than_looped_on() -> None:
    """Межа обертів існує, щоб чужа сторінка не диктувала тривалість роботи.

    Коли після `MAX_UNESCAPE_ROUNDS` ознака розмітки лишається, функція мусить
    ВІДДАТИ що є, а не крутитись: слід у тексті чесніший за нескінченний цикл.
    """
    assert MAX_UNESCAPE_ROUNDS == 2
    text = _strip_html("параметр href = значення")
    # Головне твердження: функція ПОВЕРНУЛА, хоча її власна умова зупинки не
    # виконана — ознака розмітки в результаті лишилась. Межа обертів перемагає
    # вміст. Якби цикл крутився до чистоти, цей виклик не завершився б.
    assert _RESIDUAL_MARKUP.search(text) is not None
    assert text == "параметр href = значення"


def test_stripping_plain_text_leaves_it_intact() -> None:
    """Негативне плече: попередній тест не сміє проходити на функції, що все псує."""
    assert _strip_html("звичайний текст без розмітки") == "звичайний текст без розмітки"
