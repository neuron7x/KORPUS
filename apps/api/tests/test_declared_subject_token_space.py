"""Дві множини слів мусять жити в одному просторі, інакше їхній перетин бреше мовчки.

`_extract` знімає слова оголошеного предмета з вимоги покриття рівно для того
документа, який цей предмет оголосив: стаття «Обов'язки: Днювальний парку» каже
«впускати на територію парку…» і слова «обов'язки» не містить, тож проти повного
питання її покриття 0.333 при порозі 0.5 — і вона не давала ЖОДНОЇ цитати.

Допуск для цього й існує. Він не спрацьовував, бо `subject_tokens` розбирала назву
через `\\w+`, а питання проходило `tokenize` зі зняттям закінчення. Перетин двох
різних просторів порожній — і порожній ТИХО: жодного винятку, жодного запису, лише
відсутня цитата.

Виміряно 01.09.2026 на 99 оголошених предметах: перетин порожній рівно для двох —
«Днювальний парку» і «Безпосередні командири». Решта 97 виживали випадково, бо мали
хоч одне слово, якого стемер не чіпає. І ті самі два предмети були єдиними, чий
документ бенчмарк не бачив у цитатах жодного разу.

Тому тут перевіряється НЕ значення функції, а її співмірність із розбором питання:
`tokenize` може змінитись, і тест мусить упасти лише тоді, коли дві сторони
розійшлись, а не тоді, коли обидві змінились разом.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "apps/api/src"))

from korpus.application.declared_subject import (  # noqa: E402
    subject_tokens,
    subjects_in_question,
)
from korpus.application.retrieval_math import tokenize  # noqa: E402

#: Обидва предмети інфлектовані в питанні цілком: жодне слово не переживає стемер
#: незміненим, тож жодне «випадкове» перекриття їх не рятує.
FULLY_INFLECTED = [
    ("Обов'язки: Днювальний парку (Статут, ст.358)", "Які обов'язки має днювальний парку?"),
    (
        "Обов'язки: Безпосередні командири (Статут, ст.104)",
        "Які обов'язки має безпосередні командири?",
    ),
]


@pytest.mark.parametrize(("title", "question"), FULLY_INFLECTED)
def test_the_declared_subject_is_reachable_from_the_question(title: str, question: str) -> None:
    """Єдиний споживач перетинає ці множини; порожній перетин вимикає допуск цілком."""
    assert subject_tokens([title]).intersection(tokenize(question))


def test_subject_tokens_are_produced_by_the_same_parser_as_the_question() -> None:
    """Співмірність, а не конкретні рядки: тест переживе зміну стемера, розрив — ні."""
    subject = "Начальник продовольчої служби"
    title = f"Обов'язки: {subject} (Статут, ст.156)"

    assert subject_tokens([title]) == set(tokenize(subject))


def test_a_stop_word_in_the_subject_is_not_offered_as_covered() -> None:
    """Заголовок із корпусу, не вигаданий: сім оголошених предметів містять стоп-слова.

    «на» не є токеном питання, тож документ не сміє звітувати, що покриває його
    власною назвою. Наслідку для допуску це не мало — стоп-слово не доходить і з
    боку питання, — але множина, у якій воно лежить, описує документ неправдиво.
    """
    tokens = subject_tokens(["Обов'язки: Військовий комендант на транспорті (Статут, ст.1)"])

    assert "на" not in tokens
    assert {"комендант", "транспорт"} <= tokens


def test_a_subject_the_question_does_not_name_stays_disjoint() -> None:
    """Негативний контроль: розбір, що зближує все з усім, допуску не звужує."""
    title = "Обов'язки: Днювальний парку (Статут, ст.358)"

    assert not subject_tokens([title]).intersection(tokenize("Що таке артилерійська батарея?"))


# ── Допуск за ПОЧАТКОМ слова. Людина питає родовим, роль береться із заголовка як є.


def test_the_subject_is_found_in_the_genitive() -> None:
    """Виміряно 01.09.2026: дослівний підрядок давав родовим 1 із 14, тут 13 із 14."""
    titles = ["Обов'язки: Днювальний парку (Статут, ст.358)"]

    assert subjects_in_question("Які обов'язки днювального парку?", titles) == titles


def test_the_nominative_still_works() -> None:
    """Негативний контроль до попереднього: правило, що ламає називний, не є ліками."""
    titles = ["Обов'язки: Днювальний парку (Статут, ст.358)"]

    assert subjects_in_question("Які обов'язки має днювальний парку?", titles) == titles


def test_a_neighbouring_role_is_not_admitted() -> None:
    """Збіг за початком не сміє зробити «черговий» і «днювальний» одним предметом."""
    other = ["Обов'язки: Черговий парку (Статут, ст.353)"]

    assert subjects_in_question("Які обов'язки днювального парку?", other) == []


def test_the_longer_subject_comes_first() -> None:
    """Порядок за довжиною доживає до ранжування — інакше узагальнення виграє."""
    specific = "Обов'язки: Безпосередні командири (Статут, ст.104)"
    generic = "Обов'язки: Командир (начальник) (Статут, ст.36)"

    found = subjects_in_question("Які обов'язки безпосередніх командирів?", [generic, specific])

    assert found[0] == specific


def test_a_short_function_word_does_not_block_the_subject() -> None:
    """«Інструктор ІЗ тактичної медицини» мусить знайтись питанням зі «з»."""
    titles = ["Обов'язки: Інструктор із тактичної медицини роти (Статут, ст.1)"]

    assert (
        subjects_in_question("Які обов'язки інструктора з тактичної медицини роти?", titles)
        == titles
    )


def test_a_subject_with_no_long_word_is_not_admitted() -> None:
    """Негативний контроль: предмет із самих коротких слів збігався б із будь-чим."""
    assert subjects_in_question("Що робити?", ["Обов'язки: та по із (Статут, ст.1)"]) == []


def test_a_question_about_something_else_admits_nothing() -> None:
    titles = ["Обов'язки: Днювальний парку (Статут, ст.358)"]

    assert subjects_in_question("Що таке артилерійська батарея?", titles) == []
