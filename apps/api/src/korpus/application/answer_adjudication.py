"""Кілька НЕЗАЛЕЖНИХ осей судять про одну цитату, і вирок виносить механіка.

Доктрина взята з `config/agents/axes.json`, де вона вже записана для агентів, що
працюють НАД системою, і тут застосована всередині продукту: **агент не верифікує
агента — верифікує інша вісь**. Дві осі на тих самих даних це одна вісь за подвійну
ціну; вони зійдуться, і згода буде порожньою.

Навіщо це існує. Виміряно 31.08.2026 на живому розгортанні: `evidence_coverage`,
єдине число впевненості, яке бачить читач, дорівнює 1.0 у КОЖНІЙ відповіді — воно
рахує частку claim'ів, чиї span_id є серед цитат, а кожен claim будується з
цитованого спана. Тавтологія за побудовою. Лексичне покриття питання теж не є
доречністю: телеграфний рядок «"Буг" по цілі А78 … вогонь відкрив» має покриття 0.5
на питанні «коли дозволяється відкривати вогонь по цивільній особі» і проходить
поріг, тоді як обмежувальна норма з того самого статуту не проходить.

Чотири осі, і жодна не бачить того, що бачать інші:

  lexical        скільки змістовних слів питання несе речення (вже було)
  structural     чи це проза, чи уламок верстки — прогін пробілів, початок посеред
                 речення. Дивиться на ФОРМУ, не на зміст і не на питання
  interrogative  чи несе речення ту модальність, якої вимагає ТИП питання: на «чи
                 дозволяється» потрібне дозвільне формулювання, на «хто відповідає» —
                 обов'язок. Дивиться на ПИТАННЯ, чого не робить жодна інша вісь
  contrast       чи не говорить речення про ПРОТИЛЕЖНУ категорію: питання про цивільні
                 об'єкти проти норми про воєнні. Дивиться на ПАРУ питання-цитата, і
                 єдина з чотирьох уміє спіймати підміну предмета при високому покритті

**UNKNOWN не є PASS.** Вісь, яка не може винести вирок, каже `CANNOT_ADJUDICATE`, і
це ніколи не підвищує впевненість — лише лишає її неповною. Відсутність дозвільного
формулювання не доводить недоречності: у статуті норма буває сформульована описово.
Тому інтеррогативна вісь уміє СХВАЛИТИ і УТРИМАТИСЬ, і не вміє відхилити.

Вимір, який визначив ці межі (12 питань, головний доказ живого розгортання):
вісь типу питання схвалила 3 із 8 доменних питань — тобто в 5 випадках провідна
цитата не несе тієї модальності, якої питання вимагає. Зробити це ВІДМОВОЮ означало б
відмовити на 5 із 8 своїх питань; тому вісь ранжує й розкриває, а не відхиляє.
Вісь верстки позначила рівно один випадок із десяти — той самий «Буг».
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Literal

from korpus.application.evidence import starts_mid_sentence

Verdict = Literal["SUPPORTS", "DOES_NOT_SUPPORT", "CANNOT_ADJUDICATE"]

#: Прогін пробілів — слід колонки або таблиці, витягнутої з PDF як текст. Але сам факт
#: прогону НЕ є ознакою: він трапляється всередині цілком нормального речення. Виміряно
#: 31.08.2026 на живих відповідях:
#:
#:     «"Буг" по цілі А78 … вогонь відкрив»          прогін 48 / довжина  81 = 0.59, 6 слів
#:     «If the casualty has increased difficulty…»    прогін 19 / довжина 211 = 0.09, 32 слова
#:     «lthough it may be tempting, refrain from…»    прогін 20 / довжина 179 = 0.11, 24 слова
#:
#: Перша редакція правила дивилась на ФАКТ прогону ≥8 і відхилила обидва добрі речення —
#: на замороженому еталоні це коштувало трьох кейсів, що перевернулись у
#: `requires_human_review`. Правило дивиться на ЧАСТКУ: рядок, у якому чверть довжини є
#: одним прогоном, — це колонка, а не речення.
_LAYOUT_RUN = re.compile(r"[ \t]{8,}")
#: Запас між 0.11 (найгірше з добрих) і 0.59 (погане) навмисно широкий: вужчий поріг
#: був би підігнаний під три виміряні рядки.
_LAYOUT_SHARE = 0.25

#: Тип питання → модальність, якої відповідь на нього мусить торкнутися. Таблиця, а не
#: код: рядок додається дешевше за гілку, і мутант на таблицю вбиває саме правило.
_KINDS: tuple[tuple[str, re.Pattern[str], re.Pattern[str]], ...] = (
    (
        "permission",
        re.compile(r"\b(чи\s+(можна|дозвол|є)|коли\s+дозволя|чи\s+має\s+прав|чи\s+заборон)", re.I),
        re.compile(
            r"(дозвол\w+|заборон\w+|має\s+прав\w+|не\s+допуска\w+|допуска\w+|"
            r"зобов'?язан\w+|вважа\w+\s+законн\w+|правомірн\w+)",
            re.I,
        ),
    ),
    (
        "duty",
        re.compile(r"\b(обов'?язк\w*|хто\s+відповіда|хто\s+зобов)", re.I),
        re.compile(r"(обов'?язк\w+|відповіда\w+\s+за|зобов'?язан\w+|поклада\w+)", re.I),
    ),
    (
        "quantity",
        re.compile(r"\b(скільки|який\s+строк|яка\s+тривал|протягом\s+якого)", re.I),
        re.compile(r"\d"),
    ),
)


#: Пари категорій, які в цьому домені ПРОТИЛЕЖНІ, а лексично сусідні. Вісь спрацьовує
#: лише коли категорія ПИТАННЯ у цитаті відсутня, а її протилежність присутня: тоді
#: речення говорить про інший предмет, зберігаючи майже всі слова питання.
#:
#: Випадок, заради якого вісь існує (виміряно 31.08.2026 на живому розгортанні):
#: питання «Чи є ЦИВІЛЬНІ об'єкти законними цілями для нападу?» отримувало під зеленим
#: вироком «ВОЄННІ об'єкти вважаються законними цілями для нападу.» — покриття 0.8,
#: три інші осі згодні, і різниця між правомірним ураженням і воєнним злочином — одне
#: слово, яке система замінила мовчки.
#:
#: Таблиця, а не гілки: рядок коштує рядка, і мутант, що прибирає пару, вбиває саме те
#: правило, яке нею тримається.
#:
#: ⚠ Тут лише ПРЕДМЕТИ, і ніколи МОДАЛЬНОСТІ. Перша редакція мала пару
#: «дозволяється ↔ забороняється», і власний тест її спростував за хвилину:
#: «Заборонено відкривати вогонь по цивільній особі» — це ВІДПОВІДЬ на питання «коли
#: дозволяється відкривати вогонь», а не мова про інший предмет. Протилежна модальність
#: відповідає на питання; протилежна категорія підміняє його.
_CONTRASTS: tuple[tuple[re.Pattern[str], re.Pattern[str]], ...] = tuple(
    (re.compile(left, re.I), re.compile(right, re.I))
    for left, right in (
        (r"цивільн\w*", r"(воєнн\w*|військов\w*|бойов\w*)"),
        (r"(воєнн\w*|військов\w*)", r"цивільн\w*"),
        (r"(свої\w*|власн\w*)", r"(противник\w*|ворож\w*)"),
        (r"(противник\w*|ворож\w*)", r"(свої\w*|власн\w*)"),
        (r"мирн\w*", r"бойов\w*"),
        (r"відкрива\w*", r"припиня\w*"),
    )
)


#: Ознаки того, що на вході ПИТАННЯ, а не мішок ключових слів. Дві осі нижче міркують
#: саме про питання — його тип і його предмет, — тож на не-питанні вони мусять
#: утриматись, а не судити.
#:
#: Виміряно 31.08.2026 на замороженому еталоні дерева: 3 кейси перевернулись із
#: `answered` на `requires_human_review`, і всі три — англомовні мішки слів
#: («wiping exhalation reseal trapped seal debris»). Набір складено з речень-доказів,
#: а не з питань; 0 із 79 запитів містять «?», 59 % не містять кирилиці. Вісь, що
#: судить предмет питання там, де питання немає, міряє власну вигадку.
_INTERROGATIVE_FORM = re.compile(
    r"(\?|\b(чи|коли|хто|кому|кого|як|яка|який|яке|які|що|скільки|де|куди|навіщо|"
    r"чому|яким|якої|якого)\b)",
    re.I,
)


def is_question(text: str) -> bool:
    """Чи є на вході питання. Порожній рядок питанням не є."""
    return bool(_INTERROGATIVE_FORM.search(text))


@dataclass(frozen=True)
class AxisVerdict:
    """Що сказала одна вісь і чому. Причина — для читача, не для журналу."""

    axis: str
    verdict: Verdict
    reason: str


def question_kind(question: str) -> str | None:
    """Тип питання, або None — коли жоден зразок не впізнано.

    None означає «не знаю», і далі інтеррогативна вісь утримується. Здогад про тип
    коштував би дорожче за мовчання: питання невпізнаного типу отримало б вимогу,
    якої його джерело не зобов'язане нести.
    """
    for kind, asked, _ in _KINDS:
        if asked.search(question):
            return kind
    return None


def _structural(quote: str) -> AxisVerdict:
    longest_run = max((len(match.group(0)) for match in _LAYOUT_RUN.finditer(quote)), default=0)
    if quote and longest_run / len(quote) >= _LAYOUT_SHARE:
        return AxisVerdict(
            "structural",
            "DOES_NOT_SUPPORT",
            "уривок є фрагментом верстки (колонка або таблиця), а не реченням документа",
        )
    if starts_mid_sentence(quote):
        return AxisVerdict(
            "structural",
            "CANNOT_ADJUDICATE",
            "уривок починається не з початку речення, тож його підмет міг лишитись вище",
        )
    return AxisVerdict("structural", "SUPPORTS", "ціле речення прози")


def _interrogative(question: str, quote: str) -> AxisVerdict:
    # Захисту «лише для питань» тут НЕМАЄ, і це виміряне рішення, а не недогляд.
    # Мутант, що знімав такий захист, ВИЖИВ: ця вісь уміє тільки схвалювати або
    # утримуватись, тож заборона судити не-питання нічого не боронить — вона лише
    # знімає підтримку там, де речення справді несе потрібну модальність. Захист
    # лишається на осі `contrast`, яка вміє ВІДХИЛЯТИ, і там він убивається мутантом.
    kind = question_kind(question)
    if kind is None:
        return AxisVerdict("interrogative", "CANNOT_ADJUDICATE", "тип питання не впізнано")
    marker = next(pattern for name, _, pattern in _KINDS if name == kind)
    if marker.search(quote):
        return AxisVerdict("interrogative", "SUPPORTS", f"несе формулювання типу «{kind}»")
    return AxisVerdict(
        "interrogative",
        "CANNOT_ADJUDICATE",
        f"не містить формулювання типу «{kind}» — норма може бути висловлена описово",
    )


def _contrast(question: str, quote: str) -> AxisVerdict:
    """Відхиляє, коли цитата говорить про ПРОТИЛЕЖНУ категорію.

    Умова навмисно вузька — потрібні три речі одночасно: категорія в питанні,
    її ВІДСУТНІСТЬ у цитаті й ПРИСУТНІСТЬ протилежної. Речення, що згадує обидві
    (а норма зазвичай саме така: «застосування зброї тільки проти воєнних об'єктів,
    навіть якщо на них перебувають цивільні особи»), не відхиляється.
    """
    if not is_question(question):
        return AxisVerdict("contrast", "CANNOT_ADJUDICATE", "на вході не питання")
    for asked, opposite in _CONTRASTS:
        if asked.search(question) and not asked.search(quote) and opposite.search(quote):
            return AxisVerdict(
                "contrast",
                "DOES_NOT_SUPPORT",
                "цитата говорить про протилежну категорію, ніж питання",
            )
    return AxisVerdict("contrast", "CANNOT_ADJUDICATE", "протилежної категорії не виявлено")


def _lexical(query_coverage: float, threshold: float) -> AxisVerdict:
    if query_coverage >= threshold:
        return AxisVerdict("lexical", "SUPPORTS", f"покриття питання {query_coverage:.2f}")
    return AxisVerdict(
        "lexical", "DOES_NOT_SUPPORT", f"покриття питання {query_coverage:.2f} нижче порога"
    )


def adjudicate(
    question: str, quote: str, query_coverage: float, threshold: float
) -> tuple[AxisVerdict, ...]:
    """Вироки трьох осей про одну цитату, у сталому порядку."""
    return (
        _lexical(query_coverage, threshold),
        _structural(quote),
        _interrogative(question, quote),
        _contrast(question, quote),
    )


def presentation(verdicts: tuple[AxisVerdict, ...]) -> str:
    """`supported` лише коли дві незалежні осі схвалили і жодна не відхилила.

    Одна вісь не робить підстави: саме одна вісь — лексичне покриття — і давала
    «ПІДСТАВА Є» рядку про позивний «Буг». Відхилення однієї осі важить більше за
    згоду решти, бо вона побачила те, чого інші не дивляться.
    """
    if any(item.verdict == "DOES_NOT_SUPPORT" for item in verdicts):
        return "contested"
    if sum(1 for item in verdicts if item.verdict == "SUPPORTS") >= 2:
        return "supported"
    return "tangential"
