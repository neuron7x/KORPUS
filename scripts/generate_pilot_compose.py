#!/usr/bin/env python3
"""Derive the isolated laptop profile from the canonical Compose security/runtime inputs."""

from __future__ import annotations

import argparse
import copy
import hashlib
import json
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[1]
PROFILE_RELATIVE = "deploy/pilot/compose.local.yaml"
PROJECT = "korpus-pilot"
OBJECT_VOLUME = "pilot-objects"


def application_storage(service: dict[str, Any]) -> None:
    environment = service["environment"]
    for key in list(environment):
        if key.startswith(("AWS_", "KORPUS_S3_")):
            del environment[key]
    environment.update(
        KORPUS_OBJECT_STORE_MODE="local",
        KORPUS_OBJECT_ROOT="/data/objects",
        KORPUS_QUARANTINE_OBJECT_ROOT="/data/quarantine",
    )
    service["secrets"] = [
        item
        for item in service["secrets"]
        if not (item if isinstance(item, str) else item["source"]).startswith("minio_")
    ]
    service["depends_on"].pop("minio-init")
    for mount in service["volumes"]:
        target = mount.split(":")[1] if isinstance(mount, str) else mount["target"]
        if target == "/data":
            raise ValueError("canonical /data mount changed; review pilot derivation")
    service["volumes"].append({"type": "volume", "source": OBJECT_VOLUME, "target": "/data"})


def derive(base: dict[str, Any]) -> dict[str, Any]:
    profile = copy.deepcopy(base)
    # A separate persistent identity prevents adopting a legacy S3-backed database.
    profile["name"] = PROJECT
    for name in ("minio", "minio-init"):
        profile["services"].pop(name)
    for name in ("api", "worker"):
        application_storage(profile["services"][name])
    profile["secrets"] = {
        name: value for name, value in profile["secrets"].items() if not name.startswith("minio_")
    }
    profile["volumes"].pop("minio-data")
    profile["volumes"][OBJECT_VOLUME] = None
    return profile


def render(base_text: str) -> str:
    fingerprint = hashlib.sha256(base_text.encode()).hexdigest()
    header = (
        "# Generated by scripts/generate_pilot_compose.py; do not edit by hand.\n"
        f"# Canonical docker-compose.yml sha256: {fingerprint}\n"
        "# Local laptop storage; this profile does not qualify S3 or WORM.\n"
    )
    return header + str(yaml.safe_dump(derive(yaml.safe_load(base_text)), sort_keys=False))


def current(source: Path) -> bool:
    target = source / PROFILE_RELATIVE
    try:
        return target.is_file() and target.read_text(encoding="utf-8") == render(
            (source / "docker-compose.yml").read_text(encoding="utf-8")
        )
    except (OSError, ValueError, KeyError, TypeError, yaml.YAMLError):
        return False


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        content = render((ROOT / "docker-compose.yml").read_text(encoding="utf-8"))
        target = ROOT / PROFILE_RELATIVE
        if args.check:
            valid = target.is_file() and target.read_text(encoding="utf-8") == content
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8")
            valid = True
    except (OSError, ValueError, KeyError, TypeError, yaml.YAMLError) as exc:
        print(json.dumps({"valid": False, "failure": type(exc).__name__}))
        return 1
    print(
        json.dumps(
            {
                "valid": valid,
                "profile": PROFILE_RELATIVE,
                "project": PROJECT,
                "regenerate_with": "python scripts/generate_pilot_compose.py",
            }
        )
    )
    return 0 if valid else 1


if __name__ == "__main__":
    raise SystemExit(main())
