#!/usr/bin/env python3
"""Порогу міряють відстань до найближчого спостереження З ОБОХ БОКІВ.

За одну ніч ця вада трапилась тричі, у трьох різних формах, і кожного разу гейт лишався
зеленим:

  ВСЕРЕДИНІ  `max_pdf_pages = 500` при документах 504/492/480/460/432 — стеля стояла
             в робочому діапазоні й спрацьовувала як підкидання монети. Впала на
             Статуті внутрішньої служби ЗСУ, через ЧОТИРИ сторінки.
  У ПОРОЖНЕЧІ `machine_readable > 20 слів/стор.` при спостереженнях 110–479 — розрив
             у 5,5 раза, поріг не розділив ЖОДНОЇ пари документів, тобто ніколи не
             спрацьовував і даними не перевірений.
  НЕ РОЗДІЛЯЄ `4 слів/КБ` — 9341 слово при нулі абзаців <p> з одного боку і 625 слів
             при 3.38 слів/КБ з іншого: обидва справжній вміст, поріг ділив не те.

Спільна форма: поріг сам по собі не є ні правильним, ні хибним — про нього можна судити
лише за відстанню до найближчих спостережень з обох боків. Тому це не «перевірка порога»,
а ВИМІР його положення.

МЕЖА ЦЬОГО ІНСТРУМЕНТА, і вона істотна. «Розділяє» означає ЛИШЕ те, що поріг
спрацьовував — і нічого не каже про те, чи він поділив ПРАВИЛЬНО. Перевірено на власному
випадку: поріг `4 слів/КБ` на повному каталозі дає `separates` (15 спостережень нижче,
66 вище, найближчі 3.63 і 4.18) — і при цьому серед тих 15 стоять сторінки mod.gov.ua
із 372–625 словами справжнього тексту. Поріг ділив стабільно й ділив не те.

Тому:
  in_the_void / untested  →  поріг НЕ перевірений даними: це вада, і її треба назвати;
  separates               →  поріг спрацьовував; ЧИ ПРАВИЛЬНО — окреме питання, на яке
                             цей вимір відповіді не дає й дати не може.
Друге питання вирішується лише поглядом на те, ЩО саме опинилось по різні боки.
"""

from __future__ import annotations

from dataclasses import dataclass

#: У скільки разів найближче спостереження може відстояти від порога, щоб той ще
#: вважався пов'язаним із даними. Понад це — поріг стоїть у порожнечі.
FAR_FACTOR = 3.0


@dataclass(frozen=True)
class Placement:
    threshold: float
    below: float | None  # найближче спостереження НИЖЧЕ порога
    above: float | None  # найближче спостереження ВИЩЕ порога
    n: int
    verdict: str
    note: str


#: НЕ КОЖЕН СТАЛИЙ Є ПОРОГОМ. `window_bytes = 65536` у remote_digest — це РОЗМІР
#: вікна, а не межа між двома класами: ніщо не лежить «нижче» чи «вище» нього, він не
#: розділяє й не мусить. Прогнати його через цей вимір — категорійна помилка, і вона
#: дає правдоподібний «не спрацьовував», який виглядає як вада там, де вади немає.
#: Міряти тут можна лише те, що відповідає на питання «по який бік межі цей випадок».
NOT_A_THRESHOLD = "параметр (розмір, вікно, крок), а не межа між класами — вимір незастосовний"


def _one_sided(
    threshold: float,
    below: float | None,
    above: float | None,
    total: int,
    unit: str,
) -> Placement:
    """Усі спостереження з одного боку: поріг не розділив нічого.

    Винесено окремо не заради стилю: разом із двобічним випадком ця функція мала
    складність 16 при стелі 15, і саме тут живуть два вироки, які легко сплутати —
    «стоїть у порожнечі» (розрив ≥ FAR_FACTOR, поріг не пов'язаний з даними) і «ще не
    спрацьовував» (поріг поруч, просто випадку не траплялось). Дії за ними різні.
    """
    u = f" {unit}" if unit else ""
    nearest = above if below is None else below
    #: Нуль як найближче спостереження — не «нескінченний розрив», а окремий випадок:
    #: усе виміряно щойно, і про положення порога сказати нічого.
    if not nearest:
        return Placement(
            threshold,
            below,
            above,
            total,
            "unmeasured",
            f"поріг {threshold}{u}: усі {total} спостережень на нулі — вимір щойно "
            "зроблено, про положення порога сказати нічого",
        )
    gap = nearest / threshold if above is not None else threshold / nearest
    far = gap >= FAR_FACTOR
    side = "ВИЩЕ" if below is None else "НИЖЧЕ"
    return Placement(
        threshold,
        below,
        above,
        total,
        "in_the_void" if far else "untested",
        f"поріг {threshold}{u} НЕ розділив нічого: усі {total} спостережень {side}, "
        f"найближче {nearest}{u}, розрив {gap:.1f}×"
        + (
            " — поріг стоїть у порожнечі й даними не перевірений"
            if far
            else " — поріг близький до даних, але ще жодного разу не спрацював"
        ),
    )


def place(threshold: float, observations: list[float], unit: str = "") -> Placement:
    values = sorted(float(v) for v in observations)
    if not values:
        return Placement(
            threshold,
            None,
            None,
            0,
            "unmeasured",
            "жодного спостереження: про поріг сказати нічого",
        )
    lower = [v for v in values if v <= threshold]
    upper = [v for v in values if v > threshold]
    below = lower[-1] if lower else None
    above = upper[0] if upper else None
    if below is not None and above is not None:
        u = f" {unit}" if unit else ""
        return Placement(
            threshold,
            below,
            above,
            len(values),
            "separates",
            f"поріг {threshold}{u} РОЗДІЛЯЄ: найближчі {below}{u} і {above}{u} "
            f"({len(lower)} нижче, {len(upper)} вище)",
        )
    return _one_sided(threshold, below, above, len(values), unit)


def separability(
    lower_class: list[float],
    upper_class: list[float],
    unit: str = "",
) -> tuple[str, str]:
    """Чи ця ВІСЬ узагалі здатна розділити два відомі класи — питання перед вибором порога.

    `place()` відповідає на «чи поріг перевірений даними» і мовчить про те, чи вісь,
    на якій він стоїть, розділяє класи взагалі. Знайдено на реальному випадку:
    `CARD_CEILING_BYTES = 200_000` давало `separates` (56 нижче, 25 вище), а класи
    за цією віссю ПЕРЕКРИВАЮТЬСЯ — картки 41 553–43 491 байт, документи
    34 559–1 443 866, і вісім справжніх документів лежать усередині смуги карток.
    Найменший документ МЕНШИЙ за найменшу картку. Жодне значення порога цього не
    виправить: вада не в числі, а у виборі того, що міряти.

    Вирок `axis_cannot_separate` сильніший за всі інші саме тому, що не пропонує
    підкрутити число — він каже, що шукати треба іншу величину.
    """
    u = f" {unit}" if unit else ""
    if not lower_class or not upper_class:
        return "unmeasured", "один із класів порожній: про роздільність сказати нічого"
    lo_max, up_min = max(lower_class), min(upper_class)
    lo_min, up_max = min(lower_class), max(upper_class)
    if lo_max < up_min:
        return "separable", (
            f"вісь РОЗДІЛЯЄ класи: {lo_min}–{lo_max}{u} проти {up_min}–{up_max}{u}, "
            f"проміжок {up_min - lo_max}{u} — поріг має де стати"
        )
    overlap = [v for v in upper_class if v <= lo_max]
    return "axis_cannot_separate", (
        f"вісь НЕ РОЗДІЛЯЄ класи: {lo_min}–{lo_max}{u} і {up_min}–{up_max}{u} "
        f"перекриваються, {len(overlap)} зі старшого класу лежать у смузі молодшого — "
        "жодне значення порога цього не виправить, треба інша величина"
    )


def selftest() -> int:
    cases: list[tuple[str, float, list[float], str]] = [
        ("поріг між спостереженнями", 200, [41, 372, 625, 9341], "separates"),
        ("усі спостереження вище, розрив великий", 20, [110, 200, 479], "in_the_void"),
        ("усі вище, але близько", 100, [110, 200, 479], "untested"),
        # Стеля вдвічі вища за найбільше спостереження — це СВІДОМО безпечне
        # розміщення (правило «1.5× над найбільшим»), а не порожнеча. Перша версія
        # цієї проби очікувала `in_the_void` і помилялась саме вона, не код.
        (
            "стеля вдвічі вища за дані — безпечна, але ще не спрацьовувала",
            1000,
            [110, 200, 479],
            "untested",
        ),
        ("стеля в двадцять разів вища — порожнеча", 10000, [110, 200, 479], "in_the_void"),
        ("рівно на порозі рахується нижнім", 110, [110, 200], "separates"),
        # «Розділяє» ≠ «правильний»: реальний випадок порога 4 слів/КБ, який стабільно
        # ділив корпус і ставив справжні сторінки mod.gov.ua на бік каркасів.
        (
            "розділяє, але це нічого не доводить про правильність",
            4.0,
            [1.58, 2.07, 2.44, 3.63, 4.18, 9.71, 46.84],
            "separates",
        ),
        ("жодного спостереження", 20, [], "unmeasured"),
        ("одне спостереження нижче", 500, [504], "untested"),
        # Нуль як найближче спостереження: усе виміряно щойно. Не «нескінченний розрив».
        ("усі спостереження на нулі — часовий поріг у перший день", 7, [0, 0, 0, 0], "unmeasured"),
    ]
    bad = 0
    for name, t, obs, want in cases:
        got = place(t, obs).verdict
        ok = got == want
        bad += not ok
        print(f"  {'✓' if ok else '✗'} {name}: {got}" + ("" if ok else f" (очікували {want})"))
    sep_cases = [
        ("класи не перетинаються", [1.0, 2.0, 3.0], [10.0, 20.0], "separable"),
        # Реальний випадок: картки 41553–43491, документи 34559–1443866.
        (
            "класи перекриваються — вісь не годиться",
            [41553.0, 43491.0],
            [34559.0, 43207.0, 1443866.0],
            "axis_cannot_separate",
        ),
        ("дотик межа-в-межу ще не роздільність", [1.0, 5.0], [5.0, 9.0], "axis_cannot_separate"),
        ("порожній клас", [], [1.0], "unmeasured"),
    ]
    for name, low, high, want in sep_cases:
        got, _note = separability(low, high)
        ok = got == want
        bad += not ok
        print(f"  {'✓' if ok else '✗'} роздільність осі: {name}: {got}")
    total = len(cases) + len(sep_cases)
    print(f"негативний контроль: {total - bad}/{total}")
    return 1 if bad else 0


if __name__ == "__main__":
    import sys

    if "--selftest" in sys.argv:
        raise SystemExit(selftest())
    print(place(500, [504, 492, 480, 460, 432], "стор.").note)
    print(place(20, [110.4, 215.7, 478.9], "слів/стор.").note)
    print(place(200, [41, 372, 391, 9341], "слів").note)
